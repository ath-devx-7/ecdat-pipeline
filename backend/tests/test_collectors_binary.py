def test_dynamic_symbols_prove_the_algorithms_the_binary_can_call(findings) -> None:
    symbols = {
        (f.algorithm_name, f.primitive, f.mode): f for f in with_observation(findings, "dynamic_symbol")
    }

    md5 = symbols[("MD5", Primitive.HASH, None)]
    assert md5.evidence_raw["symbols"] == ["MD5_Final", "MD5_Init", "MD5_Update"]
    assert md5.confidence is Confidence.HIGH

    assert ("SHA-1", Primitive.HASH, None) in symbols
    assert symbols[("SHA-1", Primitive.HASH, None)].evidence_raw["symbols"] == ["EVP_sha1"]

    rsa = symbols[("RSA", Primitive.UNKNOWN, None)]
    assert "RSA_generate_key_ex" in rsa.evidence_raw["symbols"]

    des_ecb = symbols[("DES", Primitive.CIPHER, "ECB")]
    assert des_ecb.evidence_raw["symbols"] == ["DES_ecb_encrypt"]
    assert ("DES", Primitive.CIPHER, None) in symbols  # DES_set_key_unchecked


def test_one_capability_is_one_finding(findings) -> None:
    """MD5_Init, MD5_Update and MD5_Final are one capability, not three rows."""
    md5 = [f for f in with_observation(findings, "dynamic_symbol") if f.algorithm_name == "MD5"]
    assert len(md5) == 1


