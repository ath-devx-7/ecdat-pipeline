def test_the_binary_evidence_is_what_the_advisor_reads(db_session, findings) -> None:
    """The soname and the banner from one binary reach §11's feasibility check together."""
    scan = Scan(
        mode=ScanMode.FILES,
        source_type=SourceType.FOLDER,
        source_ref="/tmp/whatever",
        data_lifetime_years=20,
        policy_version="2026.09",
        status=ScanStatus.RUNNING,
    )
    db_session.add(scan)
    db_session.flush()
    normalize(db_session, scan.id, findings)
    rows = list(db_session.scalars(Finding.__table__.select().where(Finding.scan_id == scan.id)))

    stored = db_session.query(Finding).filter(Finding.scan_id == scan.id).all()
    seen = ScanObservations(stored).libraries(BINARY, "openssl")

    assert sorted((o.version, o.observation) for o in seen) == [
        ("1.1", "linked_library"),
        ("1.1.1f", "library_version_string"),
    ]
    assert rows  # the normalizer stored every observation, unresolved names included
