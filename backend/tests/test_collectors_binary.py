def test_the_demo_binary_produces_a_libcrypto_dependency_finding(findings) -> None:
    """§7.2's required test. ``libcrypto.so.1.1`` is what blocks ML-KEM in the demo."""
    linked = with_observation(findings, "linked_library")

    assert [f.algorithm_name for f in linked] == ["libcrypto.so.1.1"]
    finding = linked[0]
    assert finding.evidence_raw["library"] == "openssl"
    assert finding.evidence_raw["version"] == "1.1"
    assert finding.evidence_raw["version_precision"] == "soname"
    assert finding.confidence is Confidence.HIGH
    assert finding.source_layer is SourceLayer.ARTIFACT
    assert finding.collector is CollectorName.BINARY
    assert finding.evidence_location == BINARY


def test_libc_is_not_a_crypto_library(findings) -> None:
    assert not any("libc.so" in f.algorithm_name for f in findings)


def test_the_version_banner_carries_the_release_the_soname_lacks(findings) -> None:
    """``OPENSSL_VERSION_TEXT`` in .rodata — demo/README.md §G's "useful wrinkle"."""
    banners = with_observation(findings, "library_version_string")

    assert len(banners) == 1
    banner = banners[0]
    assert banner.evidence_raw["library"] == "openssl"
    assert banner.evidence_raw["version"] == "1.1.1f"
    assert banner.evidence_raw["text"].startswith("OpenSSL 1.1.1f")
    # A string, so medium — the advisor trusts it beside the soname, not alone.
    assert banner.confidence is Confidence.MEDIUM


def test_soname_parsing_never_rounds() -> None:
    assert library_from_soname("libcrypto.so.1.1") == ("openssl", "1.1")
    assert library_from_soname("libssl.so.3") == ("openssl", "3")
    assert library_from_soname("libcrypto.so.1.0.0") == ("openssl", "1.0.0")
    assert library_from_soname("libcrypto.so") == ("openssl", None)
    assert library_from_soname("libgnutls.so.30") == ("gnutls", "30")
    assert library_from_soname("libc.so.6") is None


