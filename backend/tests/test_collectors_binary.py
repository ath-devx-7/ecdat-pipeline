# .rodata — hints, at medium
# --------------------------------------------------------------------------- #


def test_rodata_strings_that_name_algorithms_are_reported_at_medium(findings) -> None:
    strings = {f.algorithm_name: f for f in with_observation(findings, "rodata_string")}

    for expected in (
        "TLS_RSA_WITH_3DES_EDE_CBC_SHA",
        "TLS_RSA_WITH_RC4_128_MD5",
        "sha1WithRSAEncryption",
        "AES-128-CBC",
        "AES-256-GCM",
    ):
        assert expected in strings, sorted(strings)
        assert strings[expected].confidence is Confidence.MEDIUM

    # Format strings and record ids are not algorithms.
    assert "demo-settlement-0001" not in strings
    assert not any(name.startswith("suite") for name in strings)
    # The version banner is its own observation, not a string finding.
    assert not any(name.startswith("OpenSSL") for name in strings)


